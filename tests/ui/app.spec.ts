import { test, expect } from '@playwright/test';
test('photo workflow, local facts, editable review and actionable Codex execution failure', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/'); await expect(page.getByRole('heading', { name: 'Sell something good.' })).toBeVisible();
  await expect(page.locator('input[type=file]')).toBeEnabled(); await page.screenshot({ path: 'docs/evidence/desktop-editor.png', fullPage: true });
  await page.locator('input[type=file]').setInputFiles(['public/icons/icon-512.png', 'public/icons/icon-192.png']);
  await expect(page.getByAltText('Item photo 1')).toBeVisible(); await expect(page.getByAltText('Selected cover preview')).toBeVisible();
  await page.getByRole('button', { name: 'Use photo 2 as cover' }).click();
  await page.getByRole('button', { name: 'Add item details' }).click();
  await page.getByRole('textbox', { name: 'Model or item name' }).fill('Studio lamp');
  await page.getByRole('textbox', { name: 'Description', exact: false }).fill('A studio lamp, used, with the original stand.');
  await page.getByRole('textbox', { name: 'Asking price' }).fill('125');
  await page.getByLabel('Condition', { exact: false }).selectOption('Used');
  await page.getByRole('button', { name: 'Find my category' }).click();
  await expect(page.getByRole('status')).toContainText('Codex could not complete', { timeout: 20000 });
  expect(await page.getByAltText('Selected cover preview').getAttribute('src')).toBeTruthy();
  await page.getByRole('textbox', { name: 'Listing title' }).fill('Studio lamp with stand');
  await page.getByRole('textbox', { name: 'Category path' }).fill('Home > Lighting > Studio lamps');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await page.reload(); await page.getByRole('button', { name: '3 Review & list' }).click();
  await expect(page.getByRole('textbox', { name: 'Listing title' })).toHaveValue('Studio lamp with stand');
  await expect(page.getByRole('textbox', { name: 'Category path' })).toHaveValue('Home > Lighting > Studio lamps');
  expect(errors).toEqual([]);
  await page.evaluate(() => window.scrollTo(0, 0)); await page.screenshot({ path: 'docs/evidence/desktop-review.png', fullPage: true });
});
test('responsive shell, private API exclusion, first-visit offline reload and local text persistence', async ({ page, context }) => {
  await page.setViewportSize({ width: 390, height: 844 }); await page.goto('/');
  await expect(page.getByRole('button', { name: 'Add item details' })).toBeVisible();
  await page.getByRole('button', { name: 'Add item details' }).click();
  await page.getByRole('textbox', { name: 'Description', exact: false }).fill('Saved offline description');
  await page.waitForFunction(async () => !!(await navigator.serviceWorker.ready).active);
  await page.waitForTimeout(1000); await context.setOffline(true); await page.reload();
  await expect(page.getByText('Offline mode', { exact: true })).toBeAttached();
  await page.getByRole('button', { name: 'Add item details' }).click();
  await expect(page.getByRole('textbox', { name: 'Description', exact: false })).toHaveValue('Saved offline description');
  await page.getByRole('textbox', { name: 'Description', exact: false }).fill('Edited while offline');
  await page.getByRole('button', { name: 'Save', exact: true }).click(); await page.reload();
  await page.getByRole('button', { name: 'Add item details' }).click();
  await expect(page.getByRole('textbox', { name: 'Description', exact: false })).toHaveValue('Edited while offline');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  expect(await page.evaluate(async () => (await Promise.all((await caches.keys()).map(async k => (await (await caches.open(k)).keys()).map(r => new URL(r.url).pathname)))).flat().some(p => p.startsWith('/api/')))).toBe(false);
  await page.screenshot({ path: 'docs/evidence/mobile-offline.png', fullPage: true });
});
