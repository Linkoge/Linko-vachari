import { readFileSync, writeFileSync, renameSync } from 'node:fs';
import { join } from 'node:path';
import { z } from 'zod';
import { privateDir } from './config';
import { allowedUrl, type MarketplaceBrowser } from './browser';
import { WorkflowError } from './types';
export const TREE_MAX_AGE = 7 * 24 * 60 * 60_000;
const entry = z.object({ id: z.string().min(1), path: z.array(z.string().min(1)).min(1).max(12), url: z.string().url() });
const treeSchema = z.object({ fetchedAt: z.number(), categories: z.array(entry).min(1) });
export type Category = z.infer<typeof entry>;
export type Tree = z.infer<typeof treeSchema>;
export function categoryId(href: string) {
  if (!allowedUrl(href) || !/^(www\.)?mymarket\.ge$/.test(new URL(href).hostname)) return '';
  const url = new URL(href);
  const slug = url.pathname.match(/^\/(?:ka\/|en\/|ru\/)?products\/(.+?)\/?$/)?.[1];
  return url.pathname.match(/\/(?:c|category|categories)\/(\d+)(?:\/|$)/i)?.[1] || url.searchParams.get('CatID') || url.searchParams.get('category_id') || url.searchParams.get('cats')?.match(/^\d+$/)?.[0] || (slug ? 'products/' + slug.replace(/\/$/, '') : '');
}
/** The current category menu supplies a flat semantic ID/parent/label graph. */
export function categoriesFromResponse(value: unknown): Category[] {
  const node = z.object({ id: z.union([z.number().int().positive(), z.string().regex(/^\d+$/)]), parent_id: z.union([z.number().int().nonnegative(), z.string().regex(/^\d+$/)]), title: z.string().trim().min(1), seo_title: z.string().nullable().optional() });
  const payload = z.object({ statusCode: z.literal(200), data: z.array(node).min(1).max(10000) }).parse(value);
  const nodes = new Map(payload.data.map(n => [String(n.id), n]));
  if (nodes.size !== payload.data.length) throw new WorkflowError('CATEGORY_TREE', 'The live category tree contains duplicate IDs.');
  return payload.data.map(n => {
    const path = [n.title], visited = new Set([String(n.id)]); let parent = String(n.parent_id);
    while (parent !== '0') {
      const ancestor = nodes.get(parent);
      if (!ancestor || visited.has(parent) || path.length >= 12) throw new WorkflowError('CATEGORY_TREE', 'The live category tree is incomplete or cyclic.');
      path.unshift(ancestor.title); visited.add(parent); parent = String(ancestor.parent_id);
    }
    // IDs are observed, never generated by a model. Canonical paths are optional on older nodes.
    const url = n.seo_title ? new URL('/products/' + n.seo_title.replace(/^\/+/, ''), 'https://mymarket.ge').href : `https://mymarket.ge/products/?CatID=${n.id}`;
    if (!categoryId(url)) throw new WorkflowError('CATEGORY_TREE', 'The live category URL changed.');
    return { id: String(n.id), path, url };
  });
}
/** No model, fixed category IDs or publishing controls: traverse witnessed category links. */
export async function crawlCategories(browser: MarketplaceBrowser, maxPages = 5000): Promise<Category[]> {
  const page = await browser.open();
  const seen = new Map<string, Category>();
  const queue: Category[] = [];
  const started = Date.now();
  let observed: Promise<Category[]> | undefined;
  const response = (r: import('playwright').Response) => {
    const url = new URL(r.url());
    if (url.hostname === 'api.mymarket.ge' && /^\/api\/[a-z]{2}\/categories\/?$/.test(url.pathname) && r.request().method() === 'GET') {
      observed = r.json().then(categoriesFromResponse);
      // Consume an early rejection while page navigation/menu opening is still running.
      void observed.catch(() => {});
    }
  };
  page.on('response', response);
  try {
    await browser.home();
    const menu = page.getByRole('button', { name: /^(categories|all categories|კატეგორიები|ყველა კატეგორია)$/i }).or(page.getByText(/^(categories|all categories|კატეგორიები|ყველა კატეგორია)$/i)).first();
    if (await menu.isVisible().catch(() => false)) { await menu.click({ timeout: 5000 }); if (!observed) await page.waitForTimeout(1500); }
    if (observed) {
      let timer: ReturnType<typeof setTimeout> | undefined;
      try {
        const timeout = new Promise<never>((_resolve, reject) => { timer = setTimeout(() => reject(new WorkflowError('CATEGORY_TREE', 'The live category response timed out.')), 30_000); });
        return await Promise.race([observed, timeout]);
      } finally { clearTimeout(timer); }
    }
    async function collect(parent: string[] = [], parentUrl = '') {
      const links = await page.evaluate(() => {
        const roots = Array.from(document.querySelectorAll('nav[aria-label*="categor" i], [role=tree], [data-category-tree]'));
        const scopes = roots.length ? roots : [document.body];
        return scopes.flatMap(root => Array.from(root.querySelectorAll<HTMLAnchorElement>('a[href]')).map(a => {
          const path = [a.textContent?.replace(/\s+/g, ' ').replace(/\s*\(\d[\d, ]*\)\s*$/, '').trim() || ''];
          let li = a.closest('li')?.parentElement?.closest('li');
          while (li && root.contains(li)) {
            const label = li.querySelector(':scope > a, :scope > button')?.textContent?.trim();
            if (label) path.unshift(label);
            li = li.parentElement?.closest('li');
          }
          return { url: a.href, path, observedId: a.getAttribute('data-category-id') || a.getAttribute('data-cat-id') || '' };
        }));
      });
      for (const link of links) {
        const semanticId = categoryId(link.url), id = link.observedId || semanticId; if (!semanticId || (seen.has(id) || [...seen.values()].some(c => c.url === link.url)) || link.path.some(p => !p || p.length > 150)) continue;
        const slug = new URL(link.url).pathname, parentSlug = parentUrl ? new URL(parentUrl).pathname : '';
        const child = !semanticId.startsWith('products/') || (parentSlug && slug.startsWith(parentSlug.replace(/\/$/, '') + '/'));
        const path = child && parent.length && link.path[0] !== parent[0] ? [...parent, ...link.path] : link.path;
        if (path.length > 12) throw new WorkflowError('CATEGORY_TREE', 'Category tree depth changed; the previous saved tree was retained.');
        const node = { id, path, url: link.url }; seen.set(id, node); queue.push(node);
      }
    }
    await collect();
    if (!queue.length) throw new WorkflowError('CATEGORY_TREE', 'No semantic category links were found. Comparable search remains available.');
    // Visit every discovered category, including menus loaded only after opening a parent.
    for (let i = 0; i < queue.length; i++) {
      if (i >= maxPages || Date.now() - started > 8 * 60_000) throw new WorkflowError('CATEGORY_TREE', 'Category crawl reached its bound; the previous saved tree was retained.');
      await browser.go(queue[i].url, page);
      // Canonical slug URLs identify categories on the current site. Breadcrumbs supply their full labels.
      const crumbs = await page.evaluate(() => {
        const root = document.querySelector('nav[aria-label*="breadcrumb" i], [itemtype$="BreadcrumbList"], [data-breadcrumb], .breadcrumb, .breadcrumbs');
        return root ? Array.from(root.querySelectorAll('a')).map(a => ({ url: (a as HTMLAnchorElement).href, label: a.textContent?.replace(/\s+/g, ' ').trim() || '' })) : [];
      });
      const path = crumbs.filter(c => categoryId(c.url) && c.label).map(c => c.label);
      if (path.length) {
        if (crumbs.some(c => c.url.replace(/\/$/, '') === queue[i].url.replace(/\/$/, ''))) queue[i].path = path;
        else queue[i].path = [...path, queue[i].path.at(-1)!];
      }
      const more = page.getByRole('button', { name: /^(show more|see more|მეტის ნახვა)$/i }).first();
      for (let expanded = 0; expanded < 20 && await more.isVisible().catch(() => false); expanded++) {
        const before = await page.locator('a[href]').count(); await more.click({ timeout: 5000 });
        await page.waitForTimeout(100); if (await page.locator('a[href]').count() === before) break;
      }
      await collect(queue[i].path, queue[i].url);
    }
    return [...seen.values()];
  } finally { page.off('response', response); }
}
export class CategoryTree {
  constructor(public file = join(privateDir, 'category-tree.json'), public crawl = crawlCategories) {}
  read(): Tree | undefined { try { return treeSchema.parse(JSON.parse(readFileSync(this.file, 'utf8'))); } catch { return undefined; } }
  status() { const t = this.read(); return { count: t?.categories.length || 0, fetchedAt: t?.fetchedAt || null, stale: !t || Date.now() - t.fetchedAt > TREE_MAX_AGE }; }
  async refresh(browser: MarketplaceBrowser) {
    const categories = await this.crawl(browser);
    const tree = treeSchema.parse({ fetchedAt: Date.now(), categories });
    writeFileSync(this.file + '.tmp', JSON.stringify(tree), { mode: 0o600 }); renameSync(this.file + '.tmp', this.file); return tree;
  }
  async fresh(browser: MarketplaceBrowser) {
    if (!this.status().stale) return this.read();
    try { return await this.refresh(browser); } catch { return undefined; }
  }
  shortlist(tree: Tree, text: string, limit = 160) {
    const words = [...new Set(text.toLocaleLowerCase().match(/[\p{L}\p{N}]{2,}/gu) || [])];
    const ranked = tree.categories.map((c, index) => ({ c, index, score: words.reduce((n, w) => n + (c.path.join(' ').toLocaleLowerCase().includes(w) ? w.length : 0), 0) }));
    let candidates = ranked.sort((a, b) => b.score - a.score || a.index - b.index).map(r => r.c);
    // With no shared language, sample across all roots instead of sending the
    // entire tree or filling the budget with the first branch only.
    if (!ranked.some(r => r.score > 0)) {
      const branches = new Map<string, typeof candidates>();
      for (const c of candidates) { const key = c.path[0]; const branch = branches.get(key) || []; branch.push(c); branches.set(key, branch); }
      candidates = []; const groups = [...branches.values()];
      for (let i = 0; candidates.length < tree.categories.length; i++) for (const group of groups) if (group[i]) candidates.push(group[i]);
    }
    let bytes = 2;
    const result: typeof candidates = [];
    for (const c of candidates) {
      const size = Buffer.byteLength(JSON.stringify(c.path)) + 1;
      if (bytes + size > 24_000) continue;
      result.push(c); bytes += size; if (result.length >= limit) break;
    }
    return result;
  }
}
